#!/usr/bin/env python3
"""Generate the item set for the 3-rater CogBench human study (Nov 2026).

Design: 6 Bloom levels x 2 modes (standard, adversarial) x 4 passages = 48
items, generated by qwen2.5:14b with the paper's own prompts, adversarial
pairings and temperature (cogbenchv2.generation). Passages are drawn so each
(level, mode) cell uses 4 different subjects and every subject appears 6
times overall. Items are shuffled and given blind ids (C01..C48); the key
(model, mode, target level, vocab level) is written separately and is never
shown to raters.

Usage: python generate_items.py            # writes items.json and answer_key.csv
"""
import csv
import json
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
# cogbenchv2 lives next to this folder (v2/cogbenchv2) in the public repo, or in
# ../code in the original study checkout.
for cand in (HERE.parent, HERE.parent / "code"):
    if (cand / "cogbenchv2").is_dir():
        sys.path.insert(0, str(cand))
        break

from cogbenchv2.config import BLOOM_LEVELS, TEMPERATURE  # noqa: E402
from cogbenchv2.generation.extract import extract_qa  # noqa: E402
from cogbenchv2.generation.generate import generate_ollama  # noqa: E402
from cogbenchv2.generation.prompts import (  # noqa: E402
    build_adversarial_prompt, build_standard_prompt, get_adversarial_pairing,
)

MODEL = "qwen2.5:14b"
SEED = 20261107
PER_CELL = 4
MAX_TRIES = 3


def main():
    rng = random.Random(SEED)
    # passages.jsonl from https://huggingface.co/datasets/cogbench-anonymous/cogbench-passages
    src = HERE.parent / "hf-passages" / "passages.jsonl"
    if not src.exists():
        src = HERE / "passages.jsonl"
    passages = [json.loads(l) for l in open(src)]
    by_subject = {}
    for p in passages:
        by_subject.setdefault(p["subject"], []).append(p)
    subjects = sorted(by_subject)
    for s in subjects:
        rng.shuffle(by_subject[s])

    cells = [(lvl, mode) for mode in ("standard", "adversarial") for lvl in sorted(BLOOM_LEVELS)]
    # Rotate through subjects so each cell gets 4 distinct subjects and each
    # subject is used 48 / 8 = 6 times.
    used = {s: 0 for s in subjects}
    plan = []
    for i, (lvl, mode) in enumerate(cells):
        for j in range(PER_CELL):
            s = subjects[(i * PER_CELL + j) % len(subjects)]
            plan.append((lvl, mode, by_subject[s][used[s]]))
            used[s] += 1

    items = []
    for lvl, mode, p in plan:
        vocab = None
        if mode == "standard":
            prompt = build_standard_prompt(p["text"], lvl)
        else:
            vocab = get_adversarial_pairing(lvl)
            prompt = build_adversarial_prompt(p["text"], lvl, vocab)
        question = answer = raw = None
        for _ in range(MAX_TRIES):
            res = generate_ollama(MODEL, prompt, temperature=TEMPERATURE)
            raw = res["text"]
            if raw:
                question, answer = extract_qa(raw)
            if question:
                break
        print(f"{mode:11s} L{lvl} {p['subject']:16s} {'ok' if question else 'FAILED'}", flush=True)
        items.append({
            "passage_id": p["passage_id"], "subject": p["subject"], "section": p.get("section"),
            "passage_text": p["text"], "mode": mode, "target_level": lvl, "vocab_level": vocab,
            "model": MODEL, "prompt": prompt, "raw_output": raw,
            "question": question, "reference_answer": answer,
        })

    rng.shuffle(items)
    for k, it in enumerate(items, 1):
        it["item_id"] = f"C{k:02d}"
    with open(HERE / "items.json", "w") as f:
        json.dump({"model": MODEL, "seed": SEED, "temperature": TEMPERATURE, "items": items}, f, indent=2)
    with open(HERE / "answer_key.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["item_id", "passage_id", "subject", "mode", "target_level", "vocab_level", "model"])
        for it in items:
            w.writerow([it["item_id"], it["passage_id"], it["subject"], it["mode"],
                        it["target_level"], it["vocab_level"] or "", it["model"]])
    failed = [it["item_id"] for it in items if not it["question"]]
    print(f"wrote {len(items)} items; failed extraction: {failed or 'none'}")


if __name__ == "__main__":
    main()
